CREATE TABLE IF NOT EXISTS reviews (
  id INTEGER PRIMARY KEY,
  subject TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  picture TEXT NOT NULL,
  rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),
  message TEXT NOT NULL,
  date TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS reviews_by_date ON reviews(date DESC);
CREATE TABLE IF NOT EXISTS visitors (id TEXT PRIMARY KEY NOT NULL);
